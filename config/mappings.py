def add_section_alias(code):
    """F.1.1.2 -> F.1.S.1.2 형식 별칭 생성"""
    parts = code.split(".")
    if len(parts) != 4 or parts[0] != "F":
        return code
    return ".".join(parts[:2] + ["S"] + parts[2:])


code_to_value.update({
    add_section_alias(code): value
    for code, value in list(code_to_value.items())
})

